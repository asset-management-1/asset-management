namespace Haven.Shared.Enums;

/// <summary>
/// Specifies the direction to be used when sorting data.
/// </summary>
public enum SortDirection
{
    /// <summary>
    /// Sort items in ascending order (e.g. A to Z, 1 to 9).
    /// </summary>
    Ascending = 0,

    /// <summary>
    /// Sort items in descending order (e.g. Z to A, 9 to 1).
    /// </summary>
    Descending = 1
}
